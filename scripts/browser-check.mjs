import { chromium } from 'playwright-core';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const base=process.env.MONAD_DOCTOR_URL??'http://127.0.0.1:3143';
const stamp=new Date().toISOString().replace(/[:.]/g,'-');
const evidenceDir='evidence/live/ui-'+stamp;
await mkdir(evidenceDir,{recursive:true});
await mkdir('evidence/verification',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,timeout:60000});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
const record=(name)=>checks.push({name,passed:true});
async function run(name) {
 const pending=page.waitForResponse(r=>r.url()===base+'/api/diagnose'&&r.request().method()==='POST',{timeout:30000});
 await page.getByRole('button',{name:'Run diagnostic'}).click();
 const response=await pending;const report=await response.json();
 await writeFile(evidenceDir+'/'+name+'.json',JSON.stringify(report,null,2)+'\n');
 assert.equal(response.status(),200);
 await page.getByRole('button',{name:'Run diagnostic'}).waitFor();
 return report;
}
try {
 await page.goto(base,{waitUntil:'networkidle',timeout:60000});
 await page.getByRole('heading',{name:'Ready when you are.'}).waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.screenshot({path:'evidence/verification/desktop.png',fullPage:true});record('Desktop initial render without overflow');
 const health=await run('health');
 assert.ok(health.findings.some(f=>f.id==='network.mainnet'));
 await page.getByRole('heading',{name:'Monad Mainnet confirmed'}).waitFor();record('Health form returns actual Mainnet evidence');
 await page.getByText('Understand and verify this finding',{exact:true}).first().click();
 await page.getByText('What remains unknown',{exact:true}).first().waitFor();
 await page.getByText('How to verify',{exact:true}).first().waitFor();record('Finding guidance explains unknowns and verification');
 const pendingDownload=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export JSON'}).click();
 const download=await pendingDownload;await download.saveAs(evidenceDir+'/downloaded-report.json');
 const exported=JSON.parse(await readFile(evidenceDir+'/downloaded-report.json','utf8'));
 assert.equal(exported.mode,'health');assert.equal(exported.exportVersion,1);assert.ok(exported.findings[0].explanation.verify);assert.equal(exported.ruleVersion,'m3.1');assert.ok(exported.evidence.length>0);
 assert.ok(!JSON.stringify(exported).includes('https://rpc.monad.xyz'));record('JSON export downloads normalized evidence');
 await page.getByRole('button',{name:/Gas-limit analysis/}).click();
 await page.getByRole('button',{name:/Load padding example/}).click();
 const before=await run('gas-before');
 assert.ok(before.findings.some(f=>f.id==='gas.estimate-comparison'&&f.severity==='warning'));
 const estimate=before.evidence.find(e=>e.method==='eth_estimateGas')?.result;
 assert.equal(typeof estimate,'string');
 await page.getByLabel('Proposed gas limit',{exact:true}).fill(BigInt(estimate).toString());
 const after=await run('gas-after');
 assert.ok(after.findings.some(f=>f.id==='gas.estimate-comparison'&&f.severity==='pass'));record('Real gas before/after works through dashboard');
 const gasDownload=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export JSON'}).click();
 const downloadedGas=await gasDownload;await downloadedGas.saveAs(evidenceDir+'/downloaded-gas.json');
 const sharedGas=JSON.parse(await readFile(evidenceDir+'/downloaded-gas.json','utf8'));
 assert.equal(sharedGas.input.call.data,'[redacted]');
 assert.equal(sharedGas.evidence.find(e=>e.method==='eth_estimateGas').params[0].data,'[redacted]');
 assert.equal(after.input.call.data,'0x');record('Gas export redacts calldata while local report preserves evidence');
 await page.screenshot({path:'evidence/verification/desktop-gas-report.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.screenshot({path:'evidence/verification/mobile-gas-report.png',fullPage:true});record('390px mobile report has no horizontal overflow');
 await page.getByRole('button',{name:/Transaction lifecycle/}).click();
 const sampledBlock=health.evidence.find(e=>e.method==='eth_getBlockByNumber' && e.result?.transactions?.length);
 assert.ok(sampledBlock,'A sampled block must contain a transaction for the live lifecycle check');
 await page.getByLabel(/^Transaction hash/).fill(sampledBlock.result.transactions[0]);
 const tx=await run('transaction');
 assert.ok(tx.findings.some(f=>f.id==='tx.finalized'));record('Lifecycle form confirms real finalized transaction');
 await page.getByLabel(/^Transaction hash/).fill('0xbad');
 let invalidRequests=0;
 const trackInvalid=r=>{if(r.url()===base+'/api/diagnose'&&r.method()==='POST')invalidRequests++;};
 page.on('request',trackInvalid);
 await page.getByRole('button',{name:'Run diagnostic'}).click();
 await page.locator('#hash-error').filter({hasText:'Transaction hash must be'}).waitFor();
 assert.equal(invalidRequests,0);page.off('request',trackInvalid);
 record('Malformed hash produces meaningful inline error without a diagnostic request');
 assert.deepEqual(errors,[]);record('No browser JavaScript errors');
} catch(e) { checks.push({name:'Browser run',passed:false,error:e.message});await page.screenshot({path:'evidence/verification/browser-failure.png',fullPage:true});process.exitCode=1; }
finally { await browser.close();await writeFile('evidence/verification/browser-checks.json',JSON.stringify({base,checkedAt:new Date().toISOString(),checks,errors,evidenceDir},null,2)+'\n');console.log(JSON.stringify(checks,null,2)); }
